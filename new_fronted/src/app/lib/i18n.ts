export type TranslationKey = keyof typeof translations['zh-CN'];

export function t(language: LanguageCode, key: TranslationKey) {
  return translations[language][key] ?? translations['zh-CN'][key];
}

export function useAppLanguage() {
  const [language, setLanguage] = useState<LanguageCode>(() => readSettingsPreferences().language);

  useEffect(() => subscribeSettingsPreferences((prefs) => setLanguage(prefs.language)), []);

  return language;
}
